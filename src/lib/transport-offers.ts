function normalizeCityKey(city: string): string {
  const s = city
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();
  if (s === "tanger") return "tangier";
  if (s === "meknes") return "meknès";
  if (s === "tetouan") return "tétouan";
  if (s === "beni mellal") return "béni mellal";
  if (s === "al hoceima") return "al hoceïma";
  return s;
}

export function canonicalCityName(city: string): string {
  const k = normalizeCityKey(city);
  const map: Record<string, string> = {
    tangier: "Tangier",
    casablanca: "Casablanca",
    marrakech: "Marrakech",
    rabat: "Rabat",
    fes: "Fès",
    agadir: "Agadir",
    ouarzazate: "Ouarzazate",
    essaouira: "Essaouira",
    chefchaouen: "Chefchaouen",
    laayoune: "Laâyoune",
    dakhla: "Dakhla",
    kenitra: "Kenitra",
    oujda: "Oujda",
    nador: "Nador",
    meknes: "Meknes",
    "meknès": "Meknes",
    tetouan: "Tétouan",
    "tétouan": "Tétouan",
  };
  return map[k] || city.trim();
}

