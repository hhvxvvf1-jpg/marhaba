export function queryActiveTransportOffers(
  db: Database.Database,
  params: {
    originCity: string;
    destCity: string;
    mode: "intercity" | "intracity";
    carrierFilter?: "all" | OfferCarrierType;
    vehicleType?: "all" | "bus" | "train" | "tram";
    brandFilter?: string;
  }
): CorridorQueryResult {
  seedTransportOffersIfEmpty(db);
  pruneUnavailableOffers(db);

  const oKey = normalizeCityKey(params.originCity);
  const dKey = normalizeCityKey(params.destCity);
  const vType = params.vehicleType || "all";

  const allRows = (
    vType === "train" && oKey === dKey
      ? db.prepare(`SELECT * FROM transport_offers WHERE carrier_type = 'train_oncf'`).all()
      : db.prepare(`SELECT * FROM transport_offers WHERE mode = ?`).all(params.mode)
  ) as TransportOfferRecord[];

  const matchingCorridor = allRows.filter((r) => {
    if (vType === "bus" && r.carrier_type === "train_oncf") return false;
    if (vType === "train" && r.carrier_type !== "train_oncf") return false;
    if (vType === "tram" && r.carrier_type === "train_oncf") return false;
    if (params.mode === "intracity" || (vType === "train" && oKey === dKey)) {
      return normalizeCityKey(r.origin_city) === oKey;
    }
    return normalizeCityKey(r.origin_city) === oKey && normalizeCityKey(r.destination_city) === dKey;
  });

  const soldOutHiddenCount = matchingCorridor.filter((r) => r.status === "sold_out" || r.seats_left <= 0).length;

  let activeOffers = matchingCorridor
    .filter((r) => r.status === "active" && r.seats_left > 0)
    .map(hydrateOffer);

  // For intracity/tramway cities without a seeded tram/shuttle record, allow on-demand transfer request without inventing fake schedules
  if (params.mode === "intracity" && vType !== "train" && activeOffers.length === 0) {
    const cityDisplay = canonicalCityName(params.originCity);
    activeOffers = [
      {
        id: -1,
        offerCode: `TRANSFER-${oKey.toUpperCase()}`,
        mode: "intracity",
        carrierType: "taxi_transfer",
        carrierBrand: "MARHABA Airport / City Transfer",
        lineName: `${cityDisplay} Private Sedan (On-Request Quote)`,
        originCity: cityDisplay,
        destinationCity: cityDisplay,
        originStation: `${cityDisplay} Airport / Gare`,
        destinationStation: `${cityDisplay} Hotel / Medina`,
        depTime: "On demand",
        arrTime: "~30m",
        durationMins: 30,
        distanceKm: 20,
        fareMad: 150,
        stops: 0,
        amenities: ["A/C", "Door-to-Door", "Luggage 25kg"],
        seatsLeft: 4,
        isHighSpeed: false,
        sourcePortal: "marhaba.ma",
        sourceUrl: "/services?tab=transport",
        status: "active",
        validUntil: DEFAULT_VALID_UNTIL,
        lastCheckedAt: new Date().toISOString(),
      },
    ];
  }

  if (params.carrierFilter && params.carrierFilter !== "all") {
    activeOffers = activeOffers.filter((o) => o.carrierType === params.carrierFilter);
  }
  if (params.brandFilter && params.brandFilter !== "all") {
    const bf = params.brandFilter.toLowerCase();
    activeOffers = activeOffers.filter((o) => o.carrierBrand.toLowerCase().includes(bf));
  }

  const cheapestMad = activeOffers.length > 0 ? Math.min(...activeOffers.map((o) => o.fareMad)) : null;
  const fastestMins = activeOffers.length > 0 ? Math.min(...activeOffers.map((o) => o.durationMins)) : null;
  const earliestDep =
    activeOffers.length > 0
      ? [...activeOffers].sort((a, b) => a.depTime.localeCompare(b.depTime))[0].depTime
      : null;
  const lastVerifiedAt =
    activeOffers.length > 0
      ? activeOffers.map((o) => o.lastCheckedAt).sort().slice(-1)[0]
      : null;

  return {
    offers: activeOffers,
    summary: {
      activeCount: activeOffers.length,
      soldOutHiddenCount,
      cheapestMad,
      fastestMins,
      earliestDep,
      lastVerifiedAt,
    },
    externalSearchLinks: buildExternalCorridorLinks(params.originCity, params.destCity),
  };
}

export async function runLiveOfferWatchdog(db: Database.Database): Promise<{
  checkedAt: string;
  activeCount: number;
  soldOutCount: number;
  prunedCount: number;
  portals: Array<{ portal: string; url: string; reachable: boolean; httpStatus: number | null }>;
}> {
  seedTransportOffersIfEmpty(db);

  const portalUrls = [
    { portal: "oncf-voyages.ma", url: "https://www.oncf-voyages.ma" },
    { portal: "booking.ctm.ma", url: "https://booking.ctm.ma" },
    { portal: "supratours.ma", url: "https://www.supratours.ma" },
    { portal: "markoub.ma", url: "https://markoub.ma" },
  ];

  const portalResults = await Promise.all(
    portalUrls.map(async (p) => {
      try {
        const ctrl = new AbortController();
        const timer = setTimeout(() => ctrl.abort(), 3500);
        const res = await fetch(p.url, { method: "HEAD", signal: ctrl.signal, redirect: "follow" });
        clearTimeout(timer);
        const reachable = res.status > 0 && res.status !== 404 && res.status !== 410;
        return { portal: p.portal, url: p.url, reachable, httpStatus: res.status };
      } catch {
        return { portal: p.portal, url: p.url, reachable: false, httpStatus: null };
      }
    })
  );

  // If a portal explicitly returned 404 or 410 (Gone), increment failure count for its offers
  for (const pr of portalResults) {
    if (pr.httpStatus === 404 || pr.httpStatus === 410) {
      db.prepare(
        `UPDATE transport_offers SET check_failures = check_failures + 1, last_checked_at = datetime('now') WHERE source_portal = ?`
      ).run(pr.portal);
    } else if (pr.reachable) {
      db.prepare(
        `UPDATE transport_offers SET check_failures = 0, last_checked_at = datetime('now') WHERE source_portal = ? AND status = 'active'`
      ).run(pr.portal);
    }
  }

  const pruneResult = pruneUnavailableOffers(db);
  const activeCount = (db.prepare(`SELECT COUNT(*) AS cnt FROM transport_offers WHERE status = 'active'`).get() as { cnt: number }).cnt;
  const soldOutCount = (db.prepare(`SELECT COUNT(*) AS cnt FROM transport_offers WHERE status = 'sold_out'`).get() as { cnt: number }).cnt;

  return {
    checkedAt: new Date().toISOString(),
    activeCount,
    soldOutCount,
    prunedCount: pruneResult.expiredRemoved + pruneResult.removedDeleted,
    portals: portalResults,
  };
}

export function estimatePrivateTransferMad(originCity: string, destCity: string): number {
  const distanceKm = computeRouteDistanceKm(originCity, destCity);
  return Math.max(260, Math.round(distanceKm * 1.95));
}
