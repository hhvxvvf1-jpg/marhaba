export function seedTransportOffersIfEmpty(db: Database.Database) {
  const existing = (db.prepare(`SELECT COUNT(*) AS cnt FROM transport_offers`).get() as { cnt: number }).cnt;
  const v2Flag = db.prepare(`SELECT value_json FROM system_settings WHERE key = 'transport_offers_v2_seeded'`).get() as { value_json: string } | undefined;
  const v3Flag = db.prepare(`SELECT value_json FROM system_settings WHERE key = 'transport_offers_v3_tram_seeded'`).get() as { value_json: string } | undefined;
  const v4Flag = db.prepare(`SELECT value_json FROM system_settings WHERE key = 'transport_offers_v4_all_carriers_seeded'`).get() as { value_json: string } | undefined;
  if (existing > 0 && v2Flag && v3Flag && v4Flag) return;

  const insert = db.prepare(
    `INSERT OR IGNORE INTO transport_offers (
      offer_code, mode, carrier_type, carrier_brand, line_name,
      origin_city, destination_city, origin_station, destination_station,
      dep_time, arr_time, duration_mins, distance_km, fare_mad, stops,
      amenities_json, seats_left, is_high_speed, source_portal, source_url,
      status, valid_until
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`
  );

  const tx = db.transaction(() => {
    let seedList: SeedOfferTuple[] = [];
    if (existing === 0 || !v2Flag) {
      seedList = [...VERIFIED_SEED_OFFERS, ...TRAMWAY_URBAN_OFFERS, ...ALL_MOROCCO_CARRIERS_SEED];
    } else if (!v3Flag) {
      seedList = [...TRAMWAY_URBAN_OFFERS, ...ALL_MOROCCO_CARRIERS_SEED];
    } else {
      seedList = ALL_MOROCCO_CARRIERS_SEED;
    }
    for (const o of seedList) {
      insert.run(
        o.offer_code,
        o.mode,
        o.carrier_type,
        o.carrier_brand,
        o.line_name,
        o.origin_city,
        o.destination_city,
        o.origin_station,
        o.destination_station,
        o.dep_time,
        o.arr_time,
        o.duration_mins,
        o.distance_km,
        o.fare_mad,
        o.stops,
        o.amenities_json,
        o.seats_left,
        o.is_high_speed,
        o.source_portal,
        o.source_url,
        o.status,
        DEFAULT_VALID_UNTIL
      );
    }
    db.prepare(`INSERT OR REPLACE INTO system_settings (key, value_json) VALUES ('transport_offers_v2_seeded', 'true')`).run();
    db.prepare(`INSERT OR REPLACE INTO system_settings (key, value_json) VALUES ('transport_offers_v3_tram_seeded', 'true')`).run();
    db.prepare(`INSERT OR REPLACE INTO system_settings (key, value_json) VALUES ('transport_offers_v4_all_carriers_seeded', 'true')`).run();
  });
  tx();
}

/**
 * Automatic lifecycle enforcement:
 * - Any offer past `valid_until` is marked `expired` and deleted from live inventory.
 * - Any offer marked `removed` or with `check_failures >= 3` is deleted from live inventory.
 * - Any offer with `seats_left <= 0` is enforced as `sold_out` and hidden from active offers.
 */
export function pruneUnavailableOffers(db: Database.Database): {
  expiredRemoved: number;
  markedSoldOut: number;
  removedDeleted: number;
} {
  const today = new Date().toISOString().slice(0, 10);
  const soldOutRes = db
    .prepare(`UPDATE transport_offers SET status = 'sold_out' WHERE seats_left <= 0 AND status = 'active'`)
    .run();
  const expiredRes = db
    .prepare(`DELETE FROM transport_offers WHERE valid_until < ? OR status = 'expired'`)
    .run(today);
  const removedRes = db
    .prepare(`DELETE FROM transport_offers WHERE status = 'removed' OR check_failures >= 3`)
    .run();

  return {
    expiredRemoved: expiredRes.changes,
    markedSoldOut: soldOutRes.changes,
    removedDeleted: removedRes.changes,
  };
}

function hydrateOffer(row: TransportOfferRecord): HydratedTransportOffer {
  let amenities: string[] = [];
  try {
    amenities = JSON.parse(row.amenities_json || "[]");
  } catch {
    amenities = [];
  }
  return {
    id: row.id,
    offerCode: row.offer_code,
    mode: row.mode,
    carrierType: row.carrier_type,
    carrierBrand: row.carrier_brand,
    lineName: row.line_name,
    originCity: row.origin_city,
    destinationCity: row.destination_city,
    originStation: row.origin_station,
    destinationStation: row.destination_station,
    depTime: row.dep_time,
    arrTime: row.arr_time,
    durationMins: row.duration_mins,
    distanceKm: row.distance_km,
    fareMad: row.fare_mad,
    stops: row.stops,
    amenities,
    seatsLeft: row.seats_left,
    isHighSpeed: Boolean(row.is_high_speed),
    sourcePortal: row.source_portal,
    sourceUrl: row.source_url,
    status: row.status,
    validUntil: row.valid_until,
    lastCheckedAt: row.last_checked_at,
  };
}

