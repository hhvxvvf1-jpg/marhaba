export function tCity(lang: Language, city: string): string {
  const raw = (city || "").trim();
  if (!raw) return "";
  const lower = raw.toLowerCase();
  const match = MOROCCO_CITIES.find(
    (c) =>
      c.name.toLowerCase() === lower ||
      c.nameFr.toLowerCase() === lower ||
      c.nameAr === raw ||
      c.slug === lower ||
      c.aliases.some((a) => a.toLowerCase() === lower)
  );
  if (match) {
    if (lang === "ar") return match.nameAr;
    if (lang === "fr") return match.nameFr;
    return match.name;
  }
  return raw;
}

